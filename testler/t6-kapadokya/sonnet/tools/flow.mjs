import puppeteer from 'puppeteer-core';
const W = 1280, Hh = 720;
const browser = await puppeteer.launch({ executablePath: '/usr/bin/chromium', headless: 'new', args: ['--no-sandbox', '--use-angle=gl', '--ignore-gpu-blocklist', `--window-size=${W},${Hh}`, '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage(); await page.setViewport({ width: W, height: Hh });
page.on('console', m => { const t = m.text(); if (!/GL Driver|deprecated/.test(t)) console.log('[page]', t.slice(0, 300)); });
page.on('pageerror', e => console.log('[pageerror]', e.message));
await page.goto('file://' + process.cwd() + '/index.html');
await page.waitForFunction(() => document.querySelector('#loader .status').textContent === 'Hazır', { timeout: 180000 });
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
await sleep(600);
await page.screenshot({ path: 'shots/f_0_loader.png' });
await page.click('#bStart');
await sleep(4500);
await page.screenshot({ path: 'shots/f_1_tour_title.png' });
await sleep(9000);
await page.screenshot({ path: 'shots/f_2_tour_caption.png' });
await page.keyboard.press('Space');
await sleep(2500);
await page.screenshot({ path: 'shots/f_3_explore_pause.png' });
await page.mouse.click(640, 360);
await sleep(600);
await page.keyboard.down('KeyW'); await sleep(2500); await page.keyboard.up('KeyW');
await page.screenshot({ path: 'shots/f_4_walk.png' });
await page.keyboard.press('KeyF'); await page.keyboard.down('Space'); await sleep(3500); await page.keyboard.up('Space');
await page.screenshot({ path: 'shots/f_5_fly.png' });
await page.keyboard.press('KeyM'); await sleep(600);
await page.screenshot({ path: 'shots/f_6_map.png' });
await page.keyboard.press('KeyM'); await sleep(300);
console.log(JSON.stringify(await page.evaluate(() => ({ state: __k.S.state, pos: __k.S.player.pos, mode: __k.S.player.mode, active: __k.S.active, pr: __k.renderer.getPixelRatio() }))));
await browser.close();
