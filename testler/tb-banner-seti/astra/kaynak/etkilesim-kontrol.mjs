import {chromium} from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-gpu','--allow-file-access-from-files']});
const context=await browser.newContext({viewport:{width:300,height:250}});
await context.route('https://demlik.com.tr/**',r=>r.fulfill({contentType:'text/html',body:'<title>Yerel tıklama testi</title>OK'}));
const page=await context.newPage();
await page.goto('file://'+path.join(root,'html5/300x250/index.html'));
await page.evaluate(()=>{window.clickTag='https://demlik.com.tr/?kampanya=demini-al-test'});
const popupPromise=context.waitForEvent('page');
await page.locator('#exit').click({position:{x:150,y:125}});
const popup=await popupPromise;await popup.waitForLoadState();
const click={url:popup.url(),openerIsNull:await popup.evaluate(()=>window.opener===null)};await popup.close();
await page.setViewportSize({width:1440,height:900});
await page.goto('file://'+path.join(root,'onizleme.html'));
await page.locator('.motion-toggle').first().click();
await page.waitForTimeout(200);
const localPreview=await page.locator('iframe').first().evaluate(f=>!!f.contentDocument?.querySelector('svg'));
await page.locator('.motion-toggle').first().click();
const noJS=await browser.newContext({javaScriptEnabled:false,viewport:{width:300,height:250},reducedMotion:'reduce'});
const np=await noJS.newPage();await np.goto('file://'+path.join(root,'html5/300x250/index.html'));
const fallback=await np.locator('a').getAttribute('href');
const report={click,localPreview,jsDisabledFallbackHref:fallback};
await fs.writeFile(path.join(root,'kontrol/etkilesim-raporu.json'),JSON.stringify(report,null,2));
console.log(report);await browser.close();
