import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({executablePath:'/usr/bin/chromium',headless:'new',args:['--no-sandbox','--use-gl=angle','--use-angle=vulkan','--enable-features=Vulkan','--ignore-gpu-blocklist','--autoplay-policy=no-user-gesture-required','--window-size=1280,720']});
const p = await b.newPage(); await p.setViewport({width:1280,height:720});
p.on('pageerror',e=>console.log('[err]',e.message)); p.on('console',m=>{if(m.type()==='error')console.log('[cerr]',m.text().slice(0,200))});
await p.goto('file://'+process.cwd()+'/../index.html');
await p.waitForFunction('window.__ready===true',{timeout:120000});
await new Promise(r=>setTimeout(r,2500));
await p.screenshot({path:'shots/flow_intro.png'});
await p.click('#btn-begin'); await new Promise(r=>setTimeout(r,9000));
await p.screenshot({path:'shots/flow_tour.png'});
console.log('t', await p.evaluate('window.__dbg.state.t'));
await p.click('#skip'); await new Promise(r=>setTimeout(r,800));
await p.mouse.move(400,300); await p.mouse.down(); await p.mouse.move(700,340,{steps:10}); await p.mouse.up();
await p.click('#views button:nth-child(2)'); await new Promise(r=>setTimeout(r,3200));
await p.screenshot({path:'shots/flow_explore.png'});
await p.evaluate(()=>{const d=window.__dbg; d.state.mode='tour'; d.state.t=116; d.state.paused=false; document.body.dataset.mode='tour'});
await new Promise(r=>setTimeout(r,3000));
await p.screenshot({path:'shots/flow_end.png'});
await b.close();
